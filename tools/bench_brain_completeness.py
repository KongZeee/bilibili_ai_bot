async def _run() -> int:
    log = ProbeLog()
    t0 = time.time()
    scores: dict[str, float] = {}

    with tempfile.TemporaryDirectory(prefix="bench_brain_completeness_") as tmp:
        tmp_path = Path(tmp)
        brain = await _build_brain(tmp_path)
        companion = None
        try:
            companion = _build_companion(tmp_path, brain)
            log.info("companion:ready")
        except Exception as exc:
            log.info(f"companion:unavailable:{type(exc).__name__}")

        try:
            scores["memory"] = await _dim_memory(brain, log)
            scores["attention"] = await _dim_attention(brain, log)
            scores["motive"] = await _dim_motive(companion, log)
            scores["decision"] = await _dim_decision(log)
            scores["self"] = await _dim_self(companion, brain, log)
            scores["social"] = await _dim_social(brain, log)
            scores["perception"] = await _dim_perception(log)
            scores["reflection"] = await _dim_reflection(brain, log)
            scores["continuity"] = await _dim_continuity(brain, log)
            scores["presence"] = await _dim_presence(brain, companion, log)
        finally:
            close = getattr(brain, "close", None)
            if callable(close):
                try:
                    res = close()
                    if inspect.isawaitable(res):
                        await res
                except Exception:
                    pass

    # equal-weight composite 0-10
    ordered = [scores.get(d, 0.0) for d in DIMS]
    completeness = sum(ordered) / len(DIMS) if DIMS else 0.0
    wall = time.time() - t0

    for line in log.notes:
        print(line)
    for d in DIMS:
        print(f"dim_{d}:{scores.get(d, 0.0):.4f}")
    # bar chart (text)
    for d in DIMS:
        v = scores.get(d, 0.0)
        filled = int(round(v))
        bar = "█" * filled + "░" * (10 - filled)
        print(f"bar_{d}:{bar} {v:.2f}")
    print(f"completeness_score:{completeness:.4f}")
    print(f"completeness_score_100:{completeness * 10.0:.4f}")
    print(f"wall_seconds:{wall:.2f}")
    print("status:ok")
    return 0


def main() -> int:
    try:
        return asyncio.run(_run())
    except Exception as exc:
        print("completeness_score:0")
        print("completeness_score_100:0")
        print("status:crash")
        print(f"error:{type(exc).__name__}:{exc}")
        import traceback

        traceback.print_exc()
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
