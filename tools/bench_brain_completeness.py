def _clamp10(x: float) -> float:
    return max(0.0, min(10.0, float(x)))


def _rate(ok: int, total: int) -> float:
    if total <= 0:
        return 0.0
    return 100.0 * ok / total


def _has_any(text: str, needles: list[str]) -> bool:
    t = text or ""
    return any(n and n in t for n in needles)


def _blob_ctx(ctx: Any) -> str:
    parts = [
        str(getattr(ctx, "prompt_text", "") or ""),
        str(getattr(ctx, "memory_evidence", "") or ""),
        "\n".join(str(x) for x in (getattr(ctx, "recent_self_actions", ()) or ())),
    ]
    return "\n".join(parts)


def _module_source(mod: Any) -> str:
    try:
        return inspect.getsource(mod) or ""
    except Exception:
        return ""


def _file_text(*parts: str) -> str:
    path = ROOT.joinpath(*parts)
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return ""


class ProbeLog:
    def __init__(self) -> None:
        self.notes: list[str] = []

    def ok(self, dim: str, name: str, detail: str = "") -> None:
        self.notes.append(f"ok:{dim}:{name}" + (f":{detail}" if detail else ""))

    def fail(self, dim: str, name: str, detail: str = "") -> None:
        self.notes.append(f"fail:{dim}:{name}" + (f":{detail}" if detail else ""))

    def info(self, msg: str) -> None:
        self.notes.append(f"info:{msg}")


def _score_from_checks(checks: list[tuple[str, bool, float]], log: ProbeLog, dim: str) -> float:
    """Weighted sum of boolean checks, each weight in points toward 10."""
    total_w = sum(w for _, _, w in checks) or 1.0
    got = 0.0
    for name, passed, w in checks:
        if passed:
            got += w
            log.ok(dim, name, f"+{w:.2f}")
        else:
            log.fail(dim, name, f"miss_{w:.2f}")
    # normalize to 0-10 even if weights don't sum to 10
    return _clamp10(10.0 * got / total_w)


