async def _dim_attention(brain: Any, log: ProbeLog) -> float:
    """Working-memory / dual-lane attention. Capped: one-shot begin, no mid-act loop."""
    from bilibot.memory_brain.ingestion import bot_action_observation, text_observation

    checks: list[tuple[str, bool, float]] = []

    # seed a finished self act (archive terminal bot_action)
    await brain.archive_observation_async(
        bot_action_observation(
            account_id=brain.account_id,
            action_key="cmp:att:watch",
            action_type="evaluate_proactive_video",
            text="看完《海龟汤注意测试》，评分8，烧脑又好玩。",
            published=True,
            state="completed",
            scene="proactive_video",
            title="海龟汤注意测试",
        )
    )

    # noise flood
    for i in range(10):
        await brain.archive_observation_async(
            text_observation(
                account_id=brain.account_id,
                idempotency_key=f"cmp:noise:cmt:{i}",
                source_type="comment",
                event_type="comment",
                text=f"路人 评论：总结一下这个视频 第{i}次",
                title=f"噪声评论 #{i}",
                scene="reply_comment",
                importance=0.2,
            )
        )

    ctx = await brain.begin_activity(
        action_key="cmp:att:dream",
        action_type="write_dream",
        current_activity="正在整理今天的梦境，结合最近看过做过的事。",
        query="今天 最近 看了 视频 心情 念头",
        scene="dream",
        title="梦境 attention",
    )
    blob = _blob_ctx(ctx)
    checks.append(("begin_nonempty", bool(str(getattr(ctx, "prompt_text", "") or "").strip()), 1.5))
    checks.append(
        (
            "recent_self_lane",
            bool(getattr(ctx, "recent_self_actions", None)),
            1.5,
        )
    )
    checks.append(
        (
            "sees_prior_under_noise",
            _has_any(blob, ["海龟汤", "评分8", "烧脑", "点了赞", "好玩"]),
            2.5,
        )
    )
    flooded = blob.count("总结一下这个视频") >= 4 and not _has_any(
        blob, ["海龟汤", "评分8", "烧脑"]
    )
    checks.append(("not_comment_flood_only", not flooded, 1.5))

    # dual channel: evidence + recent both contribute something
    dual = bool(str(getattr(ctx, "memory_evidence", "") or "").strip()) or bool(
        getattr(ctx, "recent_self_actions", None)
    )
    checks.append(("dual_lane_present", dual, 1.0))

    # structural cap: no mid-action replan loop in service
    src = _file_text("bilibot", "memory_brain", "service.py")
    has_mid_loop = "working_memory" in src or "mid_action" in src or "replan" in src
    # reward absence? No — reward presence of continuous WM. Currently missing → fail small weight
    checks.append(("continuous_working_memory_api", has_mid_loop, 1.0))

    # one-shot generation pattern is the norm → soft structural honesty
    # (if mid-loop missing, score cannot exceed ~7.5 even if other checks full)
    raw = _score_from_checks(checks, log, "attention")
    if not has_mid_loop:
        # One-shot begin_activity is strong, but not continuous working memory.
        raw = min(raw, 6.0)
        log.info("attention_cap:no_mid_action_loop:max6.0")
    return raw


async def _dim_motive(companion: Any, log: ProbeLog) -> float:
    """Motive/desire layer. Structural honesty: schedule ≠ MotiveQueue."""
    checks: list[tuple[str, bool, float]] = []

    has_companion = companion is not None
    checks.append(("companion_present", has_companion, 1.0))
    if not has_companion:
        return _score_from_checks(checks, log, "motive")

    # energy state
    state = None
    try:
        state = companion.store.get_life_state()
    except Exception:
        state = None
    checks.append(("life_energy_field", state is not None and hasattr(state, "energy"), 1.2))

    # soft browse bias API
    checks.append(
        (
            "wants_browse_api",
            callable(getattr(companion, "wants_browse_bilibili_now", None)),
            1.0,
        )
    )

    # explore / creative maybe_* (latent motives)
    checks.append(
        ("maybe_explore_api", callable(getattr(companion, "maybe_explore", None)), 0.8)
    )
    checks.append(
        (
            "maybe_creative_api",
            callable(getattr(companion, "maybe_advance_creative", None)),
            0.8,
        )
    )

    # proactive context block uses life state
    try:
        block = ""
        if callable(getattr(companion, "build_proactive_context_block", None)):
            block = companion.build_proactive_context_block() or ""
        elif callable(getattr(companion, "get_prompt_surface", None)):
            block = companion.get_prompt_surface() or ""
        checks.append(("life_surface_nonempty_or_ready", True, 0.6))  # API reachable
        log.info(f"motive_surface_chars:{len(block)}")
    except Exception as exc:
        checks.append(("life_surface_nonempty_or_ready", False, 0.6))
        log.fail("motive", "surface_crash", type(exc).__name__)

    # energy changes after video finish
    energy_moves = False
    try:
        before = int(getattr(companion.store.get_life_state(), "energy", 70))
        companion.on_proactive_video_finished(
            title="动机测试片",
            score=9,
            mood="兴奋",
            review="想继续刷",
            comment="",
            bvid="BV1MOTIVE01",
        )
        after = int(getattr(companion.store.get_life_state(), "energy", 70))
        energy_moves = after != before or True  # finish path executed
        # stronger: energy field still in range and finish didn't crash
        energy_moves = 0 <= after <= 100
        checks.append(("energy_update_path", energy_moves, 1.2))
    except Exception as exc:
        checks.append(("energy_update_path", False, 1.2))
        log.fail("motive", "energy_path", type(exc).__name__)

    # structural: MotiveQueue / motive ranking before task dispatch
    sched = _file_text("bilibot", "scheduler.py")
    comp = _file_text("bilibot", "companion", "service.py")
    has_motive_queue = (
        "MotiveQueue" in sched
        or "motive_queue" in sched
        or "MotiveQueue" in comp
        or "select_motive" in comp
        or "rank_motives" in comp
    )
    checks.append(("motive_queue_drives_tasks", has_motive_queue, 2.4))

    # if no motive queue, hard cap — this is the honesty gate for "desire-driven"
    raw = _score_from_checks(checks, log, "motive")
    if not has_motive_queue:
        # Schedule/energy soft bias ≠ desire-driven agent.
        raw = min(raw, 5.0)
        log.info("motive_cap:no_MotiveQueue:max5.0")
    return raw


