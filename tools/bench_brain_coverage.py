def _has_any(text: str, needles: list[str]) -> bool:
    t = text or ""
    return any(n in t for n in needles if n)


def _has_all(text: str, needles: list[str]) -> bool:
    t = text or ""
    return all(n in t for n in needles if n)


async def _run() -> int:
    from bilibot.memory_brain import MemoryBrainService, RecallQuery

    with tempfile.TemporaryDirectory(prefix="bench_brain_cov_") as tmp:
        brain = MemoryBrainService("bench-acc", Path(tmp) / "bench-acc")
        seed_ids = await _seed_prior_self(brain)

        scene_pass = 0
        scene_total = len(SCENES)
        scene_rows: list[str] = []
        fail_reasons: list[str] = []

        seed_needles = ["雨夜", "青铜钥匙", "日记", "星际驿站", "小说", "唱片", "豆豆"]
        for scene, action_type, activity in SCENES:
            try:
                ctx = await brain.begin_activity(
                    action_key=f"bench:{scene}:1",
                    action_type=action_type,
                    current_activity=activity,
                    query="最近经历 雨夜 钥匙 番剧 小说 日记",
                    scene=scene,
                    recent_limit=12,
                    recall_limit=8,
                )
                prompt = str(getattr(ctx, "prompt_text", "") or "")
                recent = list(getattr(ctx, "recent_self_actions", ()) or ())
                mem = str(getattr(ctx, "memory_evidence", "") or "")
                blob = "\n".join([prompt, "\n".join(recent), mem])
                has_prompt = bool(prompt.strip())
                has_current = activity[:8] in prompt or "current_activity" in prompt
                has_memory = _has_any(blob, seed_needles)
                ok = has_prompt and has_current and has_memory
                if ok:
                    scene_pass += 1
                    scene_rows.append(f"scene_ok:{scene}")
                else:
                    reason = []
                    if not has_prompt:
                        reason.append("empty_prompt")
                    if not has_current:
                        reason.append("missing_current_activity")
                    if not has_memory:
                        reason.append("missing_seed_memory")
                    fail_reasons.append(f"{scene}:{'|'.join(reason)}")
                    scene_rows.append(f"scene_fail:{scene}:{','.join(reason)}")

                await brain.finish_activity(
                    action_key=f"bench:{scene}:1",
                    action_type=action_type,
                    result_text=f"{scene} 任务已完成（bench）。",
                    state="completed",
                    scene=scene,
                    title=scene,
                )
            except Exception as exc:
                fail_reasons.append(f"{scene}:crash:{type(exc).__name__}")
                scene_rows.append(f"scene_fail:{scene}:crash:{type(exc).__name__}")

        coverage_rate = 100.0 * scene_pass / scene_total if scene_total else 0.0

        cont_ok = 0
        cont_total = 3
        try:
            dream_ctx = await brain.begin_activity(
                action_key="bench:continuity:dream",
                action_type="dream",
                current_activity="正在做梦，回想最近看过的东西。",
                query="青铜钥匙 雨夜 唱片机",
                scene="dream",
            )
            blob = "\n".join(
                [
                    str(dream_ctx.prompt_text or ""),
                    "\n".join(dream_ctx.recent_self_actions or ()),
                    str(dream_ctx.memory_evidence or ""),
                ]
            )
            if _has_any(blob, ["青铜钥匙", "旧唱片", "雨夜", "豆豆"]):
                cont_ok += 1
            else:
                fail_reasons.append("continuity:dream_miss_seed")
        except Exception as exc:
            fail_reasons.append(f"continuity:dream_crash:{type(exc).__name__}")

        try:
            reply_ctx = await brain.begin_activity(
                action_key="bench:continuity:reply",
                action_type="reply_comment",
                current_activity="正在回复评论，结合最近经历。",
                query="你不是发过雨夜散步的动态吗？钥匙呢？",
                scene="reply_comment",
            )
            blob = "\n".join(
                [
                    str(reply_ctx.prompt_text or ""),
                    "\n".join(reply_ctx.recent_self_actions or ()),
                    str(reply_ctx.memory_evidence or ""),
                ]
            )
            if _has_any(blob, ["雨夜", "青铜钥匙", "动态", "日记", "星际驿站"]):
                cont_ok += 1
            else:
                fail_reasons.append("continuity:reply_miss_seed")
        except Exception as exc:
            fail_reasons.append(f"continuity:reply_crash:{type(exc).__name__}")

        try:
            creative_ctx = await brain.begin_activity(
                action_key="bench:continuity:creative",
                action_type="creative_chunk",
                current_activity="正在写小说下一章。",
                query="延续第三章青铜钥匙和雨夜大衣",
                scene="creative",
            )
            blob = "\n".join(
                [
                    str(creative_ctx.prompt_text or ""),
                    "\n".join(creative_ctx.recent_self_actions or ()),
                    str(creative_ctx.memory_evidence or ""),
                ]
            )
            if _has_any(blob, ["青铜钥匙", "雨夜", "大衣", "第三章", "小说"]):
                cont_ok += 1
            else:
                fail_reasons.append("continuity:creative_miss_seed")
        except Exception as exc:
            fail_reasons.append(f"continuity:creative_crash:{type(exc).__name__}")

        continuity_rate = 100.0 * cont_ok / cont_total

        # Precision suite: classic + hard (hit/reject under noise & distractors).
        prec_cases: list[tuple[str, bool]] = []

        # P1 classic hit with bvid
        hit = await brain.recall(
            RecallQuery(
                current_message="BV1COVERKEY01 里的青铜钥匙放在哪里？",
                account_id=brain.account_id,
                scene="reply_comment",
                bvid="BV1COVERKEY01",
            )
        )
        evidence = str(getattr(hit, "prompt_evidence", "") or "")
        event_ids = [
            str(ev.get("id") or ev.get("event_id") or "")
            for ev in (getattr(hit, "events", ()) or ())
            if isinstance(ev, dict)
        ]
        p1 = bool(
            seed_ids.get("video")
            and (
                seed_ids["video"] in event_ids
                or "青铜钥匙" in evidence
                or "旧唱片" in evidence
            )
        )
        prec_cases.append(("p1_video_detail", p1))
        if not p1:
            fail_reasons.append("precision:video_detail_miss")

        # P2 classic reject weather
        weather = await brain.recall(
            RecallQuery(
                current_message="今天的天气预报和午饭建议是什么？",
                account_id=brain.account_id,
                scene="reply_comment",
            )
        )
        weather_ev = str(getattr(weather, "prompt_evidence", "") or "")
        p2 = not _has_any(weather_ev, ["青铜钥匙", "旧唱片机", "雨夜散步", "星际驿站"])
        prec_cases.append(("p2_weather_clean", p2))
        if not p2:
            fail_reasons.append("precision:weather_pollution")

        # P3 hard: multi-noise "钥匙" chatter must still surface bronze location.
        noise_hit = await brain.recall(
            RecallQuery(
                current_message="青铜钥匙到底放在旧唱片机下面还是别的地方？",
                account_id=brain.account_id,
                scene="reply_comment",
            )
        )
        noise_ev = str(getattr(noise_hit, "prompt_evidence", "") or "")
        p3 = ("旧唱片机" in noise_ev or "青铜钥匙" in noise_ev) and (
            "银钥匙" not in noise_ev or "旧唱片机" in noise_ev
        )
        prec_cases.append(("p3_noise_bronze_hit", p3))
        if not p3:
            fail_reasons.append("precision:noise_bronze_miss")

        # P4 hard: entity disambiguation — bronze query must not prefer silver piano.
        disamb = await brain.recall(
            RecallQuery(
                current_message="青铜钥匙放在哪里？别和银钥匙搞混。",
                account_id=brain.account_id,
                scene="reply_comment",
            )
        )
        dis_ev = str(getattr(disamb, "prompt_evidence", "") or "")
        dis_ids = [
            str(ev.get("id") or ev.get("event_id") or "")
            for ev in (getattr(disamb, "events", ()) or ())
            if isinstance(ev, dict)
        ]
        bronze_ok = (
            seed_ids.get("video") in dis_ids
            or "旧唱片机" in dis_ev
            or ("青铜钥匙" in dis_ev and "钢琴" not in dis_ev)
        )
        silver_first = (
            seed_ids.get("video_silver") in dis_ids
            and seed_ids.get("video") not in dis_ids
            and "旧唱片机" not in dis_ev
        )
        p4 = bool(bronze_ok and not silver_first)
        prec_cases.append(("p4_disambiguate_bronze", p4))
        if not p4:
            fail_reasons.append("precision:disambiguate_fail")

        # P5 hard: conversational dynamic recall without bvid.
        conv = await brain.recall(
            RecallQuery(
                current_message="你不是发过雨夜散步的动态吗？还记得石板路吗？",
                account_id=brain.account_id,
                scene="reply_comment",
            )
        )
        conv_ev = str(getattr(conv, "prompt_evidence", "") or "")
        conv_ids = [
            str(ev.get("id") or ev.get("event_id") or "")
            for ev in (getattr(conv, "events", ()) or ())
            if isinstance(ev, dict)
        ]
        p5 = bool(
            seed_ids.get("dynamic") in conv_ids
            or _has_any(conv_ev, ["雨夜", "石板路", "路灯", "散步"])
        )
        prec_cases.append(("p5_conversational_dynamic", p5))
        if not p5:
            fail_reasons.append("precision:conversational_dynamic_miss")

        # P6 hard: reject pure arithmetic / unrelated utility query.
        util = await brain.recall(
            RecallQuery(
                current_message="帮我算一下 17*19 等于多少？再给个单位换算。",
                account_id=brain.account_id,
                scene="reply_comment",
            )
        )
        util_ev = str(getattr(util, "prompt_evidence", "") or "")
        p6 = not _has_any(
            util_ev, ["青铜钥匙", "旧唱片机", "雨夜散步", "星际驿站", "银钥匙", "钢琴"]
        )
        prec_cases.append(("p6_utility_reject", p6))
        if not p6:
            fail_reasons.append("precision:utility_pollution")

        # P7 hard: novel continuity detail under companion tick flood (activity path).
        try:
            novel_ctx = await brain.begin_activity(
                action_key="bench:precision:novel",
                action_type="creative_chunk",
                current_activity="正在续写小说，需要上一章道具位置。",
                query="第三章 大衣口袋 青铜钥匙",
                scene="creative",
                recent_limit=8,
                recall_limit=5,
            )
            novel_blob = "\n".join(
                [
                    str(novel_ctx.prompt_text or ""),
                    "\n".join(novel_ctx.recent_self_actions or ()),
                    str(novel_ctx.memory_evidence or ""),
                ]
            )
            p7 = _has_any(novel_blob, ["大衣", "第三章", "青铜钥匙", "口袋"])
            # Distinctive non-tick memory should still appear despite tick flood.
            p7 = p7 and (
                _has_any(novel_blob, ["雨夜", "动态", "星际驿站", "日记", "唱片", "小说"])
            )
        except Exception as exc:
            p7 = False
            fail_reasons.append(f"precision:novel_activity_crash:{type(exc).__name__}")
        prec_cases.append(("p7_activity_under_tick_flood", p7))
        if not p7 and "precision:novel_activity_crash" not in ";".join(fail_reasons):
            fail_reasons.append("precision:novel_activity_miss")

        # P8 hard: reject when query only shares ultra-generic tokens.
        generic = await brain.recall(
            RecallQuery(
                current_message="今天怎么样 还好吗 在吗",
                account_id=brain.account_id,
                scene="private_message",
            )
        )
        gen_ev = str(getattr(generic, "prompt_evidence", "") or "")
        p8 = not _has_any(gen_ev, ["青铜钥匙", "旧唱片机", "银钥匙", "星际驿站"])
        prec_cases.append(("p8_generic_chat_reject", p8))
        if not p8:
            fail_reasons.append("precision:generic_pollution")

        prec_ok = sum(1 for _, ok in prec_cases if ok)
        prec_total = len(prec_cases)
        precision_rate = 100.0 * prec_ok / prec_total if prec_total else 0.0

        # Primary metric: coverage 50% + continuity 20% + precision 30%
        coverage_score = (
            0.50 * coverage_rate + 0.20 * continuity_rate + 0.30 * precision_rate
        )

        print(f"coverage_score:{coverage_score:.4f}")
        print(f"coverage_rate:{coverage_rate:.4f}")
        print(f"continuity_rate:{continuity_rate:.4f}")
        print(f"precision_rate:{precision_rate:.4f}")
        print(f"hard_precision:{precision_rate:.4f}")
        print(f"scenes_passed:{scene_pass}/{scene_total}")
        print(f"continuity_passed:{cont_ok}/{cont_total}")
        print(f"precision_passed:{prec_ok}/{prec_total}")
        for name, ok in prec_cases:
            print(f"prec_{'ok' if ok else 'fail'}:{name}")
        for row in scene_rows:
            print(row)
        if fail_reasons:
            print("failures:" + ";".join(fail_reasons))
        else:
            print("failures:")
        print("status:ok")
        return 0


def main() -> int:
    try:
        return asyncio.run(_run())
    except Exception as exc:
        print("coverage_score:0")
        print("status:crash")
        print(f"error:{type(exc).__name__}:{exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
